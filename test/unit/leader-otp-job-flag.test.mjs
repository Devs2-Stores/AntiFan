// otp-fetch refuses --lock/--unlock/--renew/--since without --job (exit 2): every command pattern the worker header, the skill and
// the otp-fetch usage line hand to a worker must carry it, or the worker copies a command that cannot run.

import assert from "node:assert/strict";
import * as fs from "node:fs";
import * as path from "node:path";
import { after, describe, test } from "node:test";

import { REPO, cleanup, cli, initJob, world } from "./leader-job-cli-helpers.mjs";

after(cleanup);

const NEEDS_JOB = /--(lock|unlock|renew|since)\b/;

/** The otp-fetch command patterns of a text that read or lock but name no --job. `usage` = the `// node otp-fetch.mjs ...` lines of the script itself. */
function missingJob(text, { usage = false } = {}) {
  const bad = [];
  text.split(/\r?\n/).forEach((line, i) => {
    let segments = [];
    if (usage) {
      if (!/^\/\/\s+node otp-fetch\.mjs\b/.test(line)) return;
      segments = line.split("|");
    } else {
      segments = [...line.matchAll(/`([^`]*otp-fetch[^`]*)`/g)].map((m) => m[1]);
    }
    for (const s of segments) if (NEEDS_JOB.test(s) && !/--job\b/.test(s)) bad.push(`line ${i + 1}: ${s.trim()}`);
  });
  return bad;
}

function listFiles(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) listFiles(p, out);
    else if (/\.md$/.test(e.name)) out.push(p);
  }
  return out;
}

describe("otp-fetch command patterns always carry --job", () => {
  test("the checker flags a pattern without --job and accepts one with it", () => {
    assert.equal(missingJob("`node x/otp-fetch.mjs --since <t0> --wait 120`").length, 1);
    assert.equal(missingJob("`node x/otp-fetch.mjs --lock`").length, 1);
    assert.equal(missingJob("`node x/otp-fetch.mjs --since <t0> --wait 120 --job <job>`").length, 0);
    assert.equal(missingJob("`otp-fetch.mjs --clear` and `otp-fetch.mjs --now`").length, 0, "--clear and --now take no --job");
  });

  test("worker header templates and the antifan-leader skill name --job on every lock/read command", () => {
    const files = [...listFiles(path.join(REPO, "scripts", "leader", "templates")), ...listFiles(path.join(REPO, "skills", "antifan-leader"))];
    assert.ok(files.length >= 8);
    const problems = [];
    for (const f of files) for (const b of missingJob(fs.readFileSync(f, "utf8"))) problems.push(`${path.relative(REPO, f)} ${b}`);
    assert.deepEqual(problems, []);
  });

  test("the usage lines at the top of otp-fetch.mjs name --job on --since and the lock commands", () => {
    const text = fs.readFileSync(path.join(REPO, "scripts", "leader", "otp-fetch.mjs"), "utf8");
    assert.deepEqual(missingJob(text, { usage: true }), []);
  });

  test("prompts generated by init (feedback skeleton and ad-hoc skeleton) carry no lock/read command without --job", () => {
    const w = world();
    const feedback = initJob(w, "otpflag");
    const prompts = fs.readdirSync(feedback.dir).filter((f) => f.endsWith(".prompt.md")).map((f) => path.join(feedback.dir, f));
    const adhoc = cli(w, ["init", "--kind", "adhoc", "--slug", "otpflag-adhoc"]);
    assert.equal(adhoc.code, 0, adhoc.stderr);
    prompts.push(adhoc.last.promptPath);
    assert.equal(prompts.length, 2);
    for (const p of prompts) {
      const text = fs.readFileSync(p, "utf8");
      assert.match(text, /otp-fetch/, `${path.basename(p)} still names the OTP helper`);
      assert.deepEqual(missingJob(text), [], path.basename(p));
    }
  });
});

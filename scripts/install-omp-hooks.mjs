#!/usr/bin/env node
/**
 * Install the AntiFan OMP hooks into the user-scope hook directories.
 *
 * The user hooks directory is live for every session on this machine, so it is
 * never edited by hand: this script bundles each hook from repo source, backs up
 * whatever it replaces, and can prove what is installed (`--check`) or undo it
 * (`--rollback`).
 *
 *   node scripts/install-omp-hooks.mjs --check      # hash comparison, no writes
 *   node scripts/install-omp-hooks.mjs --install    # atomic replace + manifest
 *   node scripts/install-omp-hooks.mjs --rollback   # restore the previous files
 *
 * Discovery rule (omp://hooks.md): `<agentDir>/hooks/{pre,post}/*.{ts,js}`, where
 * `<agentDir>` defaults to `~/.omp/agent` and follows `PI_CODING_AGENT_DIR`.
 */

import { createHash } from "node:crypto";
import * as esbuild from "esbuild";
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const AGENT_DIR = process.env.PI_CODING_AGENT_DIR
  ? path.resolve(process.env.PI_CODING_AGENT_DIR)
  : path.join(os.homedir(), ".omp", "agent");
const HOOKS_DIR = path.join(AGENT_DIR, "hooks");
const MANIFEST = path.join(HOOKS_DIR, ".antifan-hooks.json");

/**
 * Self-contained ESM: no node_modules resolution happens at load time in a customer
 * workspace, and the installed file exports a real `default` factory.
 *
 * ESM, not CJS: `omp`'s extension runner extracts the factory with
 * `typeof mod === "function" ? mod : mod.default` after importing the file, and a
 * bundled CJS module does not survive that path (observed live: "Extension does not
 * export a valid factory function" for both hooks while the same bytes imported by
 * hand in Bun did expose a function `default`). Discovery only scans `*.{ts,js}`, so
 * the file must stay `.js` - the loader is syntax-driven, not extension-driven.
 */
const BUNDLE = {
  bundle: true,
  write: false,
  format: "esm",
  platform: "node",
  target: "node20",
  logLevel: "silent",
  legalComments: "none",
};

/**
 * Repo sources keep their short module names; the installed files are prefixed
 * because `~/.omp/agent/hooks/` is shared with every other hook on the machine.
 * `legacyNames` are the un-prefixed files an earlier manual install left behind -
 * they are parked on install so discovery never loads two copies of one gate.
 */
const HOOKS = [
  {
    id: "edit-guard",
    installName: "antifan-edit-guard",
    phase: "pre",
    source: "src/omp-hooks/edit-guard.ts",
    legacyNames: [],
  },
  {
    id: "run-state",
    installName: "antifan-run-state",
    phase: "pre",
    source: "src/omp-hooks/run-state.ts",
    legacyNames: [],
  },
  {
    id: "theme-qa-gate",
    installName: "antifan-theme-qa-gate",
    phase: "post",
    source: "src/omp-hooks/theme-qa-gate.ts",
    legacyNames: ["theme-qa-gate.ts"],
  },
];

function sha256(text) {
  return createHash("sha256").update(text).digest("hex");
}

function readManifest() {
  try {
    return JSON.parse(fs.readFileSync(MANIFEST, "utf8"));
  } catch {
    return null;
  }
}

async function bundleHook(hook) {
  const entry = path.join(ROOT, hook.source);
  if (!fs.existsSync(entry)) {
    if (hook.optional) return null;
    throw new Error(`missing hook source: ${hook.source}`);
  }
  const result = await esbuild.build({ ...BUNDLE, entryPoints: [entry] });
  const banner =
    `/* AntiFan hook "${hook.id}" - generated by scripts/install-omp-hooks.mjs from ${hook.source}. ` +
    `Do not edit: edit the source and re-run the installer. */\n`;
  const text = banner + result.outputFiles[0].text;
  const dir = path.join(HOOKS_DIR, hook.phase);
  return {
    ...hook,
    text,
    hash: sha256(text),
    target: path.join(dir, `${hook.installName}.js`),
    supersede: [`${hook.installName}.ts`, ...(hook.legacyNames ?? [])].map((name) =>
      path.join(dir, name),
    ),
  };
}

/** Bundles every hook first so a build failure never leaves a half-installed set. */
async function bundleAll() {
  const bundled = [];
  for (const hook of HOOKS) {
    const entry = await bundleHook(hook);
    if (entry === null) {
      console.log(`${hook.id.padEnd(16)} SKIPPED_ABSENT   (${hook.source} not present)`);
      continue;
    }
    bundled.push(entry);
  }
  return bundled;
}

async function check() {
  const bundle = await bundleAll();
  const manifest = readManifest();
  let drifted = 0;
  for (const hook of bundle) {
    const installed = fs.existsSync(hook.target) ? fs.readFileSync(hook.target, "utf8") : null;
    const recorded = manifest?.hooks?.find((entry) => entry.path === hook.target)?.sha256 ?? null;
    let state;
    if (installed === null) state = "MISSING";
    else if (sha256(installed) !== hook.hash) state = "STALE";
    else if (recorded !== null && recorded !== hook.hash) state = "STALE";
    else state = "IN_SYNC";
    if (state !== "IN_SYNC") drifted += 1;
    console.log(`${hook.id.padEnd(16)} ${state.padEnd(15)} ${hook.target}`);
  }
  if (drifted > 0) console.log(`\n${drifted} hook(s) not in sync - run: node scripts/install-omp-hooks.mjs --install`);
  return drifted === 0 ? 0 : 1;
}

async function install() {
  const bundle = await bundleAll();
  fs.mkdirSync(HOOKS_DIR, { recursive: true });
  const records = [];
  for (const hook of bundle) {
    fs.mkdirSync(path.dirname(hook.target), { recursive: true });
    for (const earlier of hook.supersede) {
      if (fs.existsSync(earlier)) {
        fs.renameSync(earlier, `${earlier}.bak`);
        console.log(`${hook.id.padEnd(16)} superseded      ${earlier} -> ${earlier}.bak`);
      }
    }
    if (fs.existsSync(hook.target)) {
      fs.copyFileSync(hook.target, `${hook.target}.bak`);
    }
    const temp = `${hook.target}.tmp`;
    fs.writeFileSync(temp, hook.text, "utf8");
    fs.renameSync(temp, hook.target);
    records.push({
      id: hook.id,
      path: hook.target,
      sha256: hook.hash,
      source: hook.source,
      superseded: hook.supersede,
    });
    console.log(`${hook.id.padEnd(16)} INSTALLED       ${hook.target}  sha256=${hook.hash.slice(0, 12)}`);
  }
  const manifest = {
    schema: 1,
    installedAt: new Date().toISOString(),
    repoRoot: ROOT,
    node: process.version,
    hooks: records,
  };
  fs.writeFileSync(MANIFEST, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
  console.log(`\nmanifest: ${MANIFEST}`);
  return 0;
}

function rollback() {
  const manifest = readManifest();
  const hooks =
    manifest?.hooks ??
    HOOKS.map((hook) => ({
      id: hook.id,
      path: path.join(HOOKS_DIR, hook.phase, `${hook.installName}.js`),
      superseded: (hook.legacyNames ?? []).map((name) => path.join(HOOKS_DIR, hook.phase, name)),
    }));
  let restored = 0;
  for (const hook of hooks) {
    const backup = `${hook.path}.bak`;
    if (fs.existsSync(backup)) {
      fs.copyFileSync(backup, hook.path);
      restored += 1;
      console.log(`${hook.id.padEnd(16)} RESTORED        ${hook.path}`);
    } else if (fs.existsSync(hook.path)) {
      fs.renameSync(hook.path, `${hook.path}.discarded`);
      console.log(`${hook.id.padEnd(16)} DISCARDED       ${hook.path} (no backup)`);
    } else {
      console.log(`${hook.id.padEnd(16)} NO_BACKUP       ${hook.path}`);
    }
    for (const earlier of hook.superseded ?? []) {
      if (fs.existsSync(`${earlier}.bak`)) {
        fs.renameSync(`${earlier}.bak`, earlier);
        console.log(`${hook.id.padEnd(16)} RESTORED        ${earlier}`);
      }
    }
  }
  console.log(`\n${restored} hook(s) restored from backup; manifest left in place at ${MANIFEST}`);
  return 0;
}

const mode = process.argv.includes("--install")
  ? "install"
  : process.argv.includes("--rollback")
    ? "rollback"
    : "check";

try {
  const code = mode === "install" ? await install() : mode === "rollback" ? rollback() : await check();
  process.exit(code);
} catch (error) {
  console.error(`[install-omp-hooks] ${mode} failed: ${error?.message ?? error}`);
  process.exit(2);
}
